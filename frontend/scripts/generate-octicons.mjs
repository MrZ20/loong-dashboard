#!/usr/bin/env node
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const sourceRoot = path.join(root, "src");
const data = JSON.parse(
  readFileSync(path.join(root, "node_modules/@primer/octicons/build/data.json"), "utf8"),
);

function sourceFiles(directory) {
  return readdirSync(directory, { withFileTypes: true }).flatMap((entry) => {
    const target = path.join(directory, entry.name);
    if (entry.isDirectory()) {
      return entry.name === "generated" ? [] : sourceFiles(target);
    }
    return /\.(ts|vue)$/.test(entry.name) ? [target] : [];
  });
}

const names = new Set(["question"]);
for (const file of sourceFiles(sourceRoot)) {
  const source = readFileSync(file, "utf8");
  for (const match of source.matchAll(/["']([a-z][a-z0-9-]+)["']/g)) {
    if (data[match[1]]) names.add(match[1]);
  }
}

const selected = Object.fromEntries(
  [...names].sort().map((name) => [
    name,
    {
      heights: Object.fromEntries(
        Object.entries(data[name].heights).map(([height, icon]) => [
          height,
          { width: icon.width, path: icon.path },
        ]),
      ),
    },
  ]),
);

const output = `// Generated by scripts/generate-octicons.mjs. Do not edit manually.\n` +
  `export const octicons = ${JSON.stringify(selected)} as const;\n`;
const generatedRoot = path.join(sourceRoot, "generated");
mkdirSync(generatedRoot, { recursive: true });
writeFileSync(path.join(generatedRoot, "octicons.ts"), output);
